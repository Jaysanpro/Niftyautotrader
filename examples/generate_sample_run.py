#!/usr/bin/env python3
"""Regenerate ``docs/sample_run.md``.

Uses the synthetic provider and the offline engine with a fixed seed, so the
committed sample is reproducible by anyone with no API key and no network. Run
it after any change that alters report structure or agent output.
"""

from __future__ import annotations

import logging
from pathlib import Path

from tradingagents_in.graph.runner import IndianTradingAgents

CONFIG = {
    "llm_provider": "offline",
    "data_provider": "synthetic",
    "online_tools": False,
    "enable_memory": False,
    "synthetic_seed": 20260101,
    "log_level": "ERROR",
    "capital_inr": 1_000_000,
    "max_debate_rounds": 2,
}

HEADER = """<!-- Generated by examples/generate_sample_run.py. Do not edit by hand. -->

# Sample run — full multi-agent debate

Produced by:

```bash
python examples/generate_sample_run.py
```

**Read the provenance before the conclusion.** This run uses the deterministic
`synthetic` data provider and the `offline` LLM engine, with a fixed seed. That
makes it byte-for-byte reproducible on any machine with no API key and no
network — which is the point of publishing it — but it also means:

- the prices are a seeded random walk, not Reliance's actual tape;
- the "reasoning" is the deterministic baseline every agent computes *before*
  an LLM is consulted, so the prose is templated rather than written.

With a real provider configured (`ITA_LLM_PROVIDER=anthropic`,
`ITA_DATA_PROVIDER=yfinance`) the same pipeline runs against live NSE data and
the LLM rewrites each section on top of this baseline. The structure, the
numbers that flow between agents, and every risk decision below are exactly what
you get in production; only the tape and the wording change.

---

"""


def main() -> None:
    app = IndianTradingAgents(config=CONFIG, use_langgraph=False)
    logging.disable(logging.CRITICAL)

    decision = app.analyse("RELIANCE.NS", run_id="SAMPLE-RELIANCE-01", save=False)
    target = Path(__file__).resolve().parent.parent / "docs" / "sample_run.md"
    target.parent.mkdir(exist_ok=True)
    target.write_text(HEADER + app.report(decision), encoding="utf-8")

    logging.disable(logging.NOTSET)
    print(f"wrote {target} — {decision.headline()}")


if __name__ == "__main__":
    main()
